import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { buildResults, computeScores } from '@/engine/launch-tests';
import { resourcesRulesets, eventsRulesets } from '@/engine/rule-deps.generated';
import type { ChecklistFile } from '@/lib/engine-assets';
import type { EngineRow } from '@/lib/types';

const checklist: ChecklistFile = JSON.parse(
  readFileSync(
    fileURLToPath(new URL('../public/checklists/fr/900-opquast-v5.json', import.meta.url)),
    'utf8',
  ),
);

const ids = Object.keys(checklist);

describe('buildResults', () => {
  it('returns exactly one row per checklist criterion', () => {
    const rows = buildResults([], checklist);
    expect(rows.length).toBe(ids.length);
    expect(new Set(rows.map((r) => r.id)).size).toBe(ids.length);
  });

  it('fills nt + auto:false for criteria with no engine result (manual criteria)', () => {
    const rows = buildResults([], checklist);
    expect(rows.every((r) => r.result === 'nt' && r.auto === false)).toBe(true);
  });

  it('keeps an engine result when the criterion does not depend on a stubbed input', () => {
    // pick a criterion id that is NOT in any forced-nt set
    const plainId = ids.find((id) => !resourcesRulesets.has(id) && !eventsRulesets.has(id))!;
    const engineRows: EngineRow[] = [
      { id: plainId, result: 'nc', details: [{ tag: 'img' }], comment: 'x' },
    ];
    const rows = buildResults(engineRows, checklist);
    const row = rows.find((r) => r.id === plainId)!;
    expect(row.result).toBe('nc');
    expect(row.auto).toBe(true);
    expect(row.forcedNt).toBe(false);
    expect(row.details.length).toBe(1);
  });

  it('forces nt for a resource-dependent criterion until resources are recovered', () => {
    const resId = ids.find((id) => resourcesRulesets.has(id));
    if (!resId) return; // the sample checklist may not include any; skip gracefully
    const engineRows: EngineRow[] = [{ id: resId, result: 'c' }];

    const stubbed = buildResults(engineRows, checklist, {
      events: false,
      resources: false,
    });
    expect(stubbed.find((r) => r.id === resId)!.result).toBe('nt');
    expect(stubbed.find((r) => r.id === resId)!.forcedNt).toBe(true);

    // once resources are recovered, the real engine result is kept
    const recovered = buildResults(engineRows, checklist, {
      events: false,
      resources: true,
    });
    expect(recovered.find((r) => r.id === resId)!.result).toBe('c');
    expect(recovered.find((r) => r.id === resId)!.forcedNt).toBe(false);
  });

  it('forces nt for an events-dependent criterion while listeners are not recovered', () => {
    // The background never recovers addEventListener handlers: these must not show a verdict.
    const evId = ids.find((id) => eventsRulesets.has(id));
    expect(evId).toBeDefined(); // V5 has some (54421, 54440)
    const engineRows: EngineRow[] = [{ id: evId!, result: 'nc' }];

    const shipped = buildResults(engineRows, checklist, { events: false, resources: true });
    expect(shipped.find((r) => r.id === evId)).toMatchObject({ result: 'nt', forcedNt: true });

    const recovered = buildResults(engineRows, checklist, { events: true, resources: true });
    expect(recovered.find((r) => r.id === evId)).toMatchObject({ result: 'nc', forcedNt: false });
  });
});

describe('computeScores', () => {
  it('counts statuses and computes conformance over decided automated criteria', () => {
    const rows = buildResults(
      [
        { id: ids[0]!, result: 'c' },
        { id: ids[1]!, result: 'nc' },
        { id: ids[2]!, result: 'c' },
      ],
      checklist,
    );
    const s = computeScores(rows);
    expect(s.total).toBe(ids.length);
    // conformance = c / (c + nc); but forced-nt may reduce decided counts, so just sanity-check bounds
    if (s.conformance !== null) {
      expect(s.conformance).toBeGreaterThanOrEqual(0);
      expect(s.conformance).toBeLessThanOrEqual(1);
    }
  });
});

describe('rule dependency catalogue', () => {
  // Generated by scripts/sync-assets.mjs from the engine and overlay sources. These memberships
  // decide which criteria are forced to "nt" when an input is not recovered.
  it('knows which V5 criteria need event listeners', () => {
    expect([...eventsRulesets].sort()).toEqual(['54421', '54440']);
  });

  it('counts the header rules, reached through helpers, as needing resources', () => {
    // CSP, X-Frame-Options, UTF-8, server leak, cache, gzip, HTTPS everywhere
    for (const id of ['54167', '54381', '54463', '54493', '54506', '54531', '54532']) {
      expect(resourcesRulesets.has(id), id).toBe(true);
    }
  });

  it('does not count a pure-DOM rule that merely sits next to the helpers', () => {
    expect(resourcesRulesets.has('54521')).toBe(false); // inline JS not minified
  });
});
