import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'wxt';

const ROOT = dirname(fileURLToPath(import.meta.url));

// MV3 extension, built for both Chrome and Firefox from a single codebase.
// The Opquast analysis engine (vendored, unmodified, in packages/opquast-test-runner)
// is injected on demand into the inspected page via chrome.scripting; its data files
// (rules.json / rulesets.json / the engine libs) are packaged under /engine/* and read by the
// extension's own pages, never exposed to sites (see manifest below). scripts/sync-assets.mjs
// populates public/.
export default defineConfig({
  srcDir: 'src',
  // Force MV3 on both targets (wxt defaults Firefox to MV2).
  manifestVersion: 3,
  // Populate public/{engine,checklists,_locales,test-descriptions} and src/engine/rule-deps.generated.ts
  // from the pristine submodules before every build / dev run. In `npm run dev` an overlay edit not
  // yet recorded in overlay.json is allowed (stamped "+dev"): the guard is a release gate.
  hooks: {
    'build:before': (wxt) => {
      const env = { ...process.env };
      if (wxt.config.command === 'serve') env.ALLOW_OVERLAY_DRIFT ??= '1';
      execFileSync('node', [join(ROOT, 'scripts/sync-assets.mjs')], { stdio: 'inherit', env });
    },
  },
  // The Firefox sources zip goes to AMO reviewers: it must rebuild the add-on and nothing more.
  // WXT ignores .gitignore here, so leave out the local scratch dirs, the packaged releases, and the
  // engine's tests and build output (sync-assets reads only its package.json and data/).
  zip: {
    excludeSources: [
      'tmp/**',
      'dist/**',
      'test/e2e/.build/**',
      'test/e2e/out/**',
      'packages/opquast-test-runner/test/**',
      'packages/opquast-test-runner/dist/**',
      'packages/opquast-test-runner/node_modules/**',
      '**/.DS_Store',
    ],
  },
  manifest: ({ browser }) => ({
    // Localized store listing: __MSG_*__ resolves against public/_locales/<locale>/messages.json
    // (generated by sync-assets from EXT_CHROME). default_locale is the fallback (en).
    name: '__MSG_extName__',
    description: '__MSG_extDescription__',
    default_locale: 'en',
    // `tabs` is intentionally NOT requested: the inspected tab's URL and loading status are
    // readable via the `<all_urls>` host permission. Keeping the set minimal eases AMO/CWS review.
    // See PERMISSIONS.md.
    permissions: ['scripting', 'activeTab', 'storage', 'unlimitedStorage'],
    host_permissions: ['<all_urls>'],
    // Firefox MV3 needs a stable add-on id. Chrome would only warn about an unknown key.
    ...(browser === 'firefox' && {
      browser_specific_settings: {
        gecko: {
          id: 'opquast-devtools@opquast.com',
          strict_min_version: '128.0',
          // Firefox 140+ data-collection consent. Schema is { required: [...] }; "none" declares that
          // the add-on collects no data (matches PRIVACY.md). WXT 0.20's manifest types don't yet
          // include this key, so cast to satisfy tsc (the manifest ships it verbatim). Ignored by
          // Firefox < 140 (AMO emits a non-blocking version warning at strict_min_version 128).
          data_collection_permissions: { required: ['none'] } as any,
        },
      },
    }),
    // No web_accessible_resources: the engine is injected with scripting.executeScript({ files })
    // and the checklists are fetched by the background and the extension's pages: neither needs them.
    // Declaring them would let any site detect the extension by fetching its files.
    // options_ui comes from src/entrypoints/options/index.html (open in a tab: its meta tag).
  }),
});
